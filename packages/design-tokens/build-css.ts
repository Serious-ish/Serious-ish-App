// Generates the moderation page's CSS variables from palette.ts, so the two surfaces cannot
// drift apart (TRD 2.6, Frontend Specification 8.1). Light under :root, dark under
// prefers-color-scheme; staff get no manual switch.
//
// Usage: node build-css.ts <output file>   (Node 24 runs TypeScript directly)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

import { palette, screenGlow, type Theme } from './palette.ts';

// Colour tokens only; depth values (shc, shk, raiseline) are emitted as plain variables too.
const colourNames = (Object.keys(palette.light) as (keyof Theme)[]).filter((k) =>
  /^(#|rgba\()/.test(String(palette.light[k])),
);

const block = (t: Theme, pad: string) =>
  Object.entries(t)
    .map(([k, v]) => `${pad}--${k}: ${v};`)
    .join('\n');

const css = `/* Generated by packages/design-tokens/build-css.ts from palette.ts. Do not edit. */

:root {
${block(palette.light, '  ')}
  --glow: ${screenGlow('var(--surf)')};
}

@media (prefers-color-scheme: dark) {
  :root {
${block(palette.dark, '    ')}
  }
}

/* Tailwind colour utilities use the tokens only: bg-brand, text-ink, border-muted. */
@theme inline {
  --color-*: initial;
${colourNames.map((k) => `  --color-${k}: var(--${k});`).join('\n')}
}
`;

const out = process.argv[2];
if (out) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, css);
} else {
  process.stdout.write(css);
}
